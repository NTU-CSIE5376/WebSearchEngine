"""Build the CSV and SQL that write resolved google.com/goto golden URLs back to metric_url.

Input is the SQLite state file of scripts/resolve_golden_goto.py: `golden` holds the
batch's metric_url rows (id, url, ...) and `goto` maps each goto link to the 302
Location it answered with. Only rows whose link resolved are written.

    python scripts/golden_goto_writeback/build_writeback.py \
        --state goto_batch21.sqlite --batch 21 --out scripts/golden_goto_writeback

Writes batch<N>_goto_resolved.csv, batch<N>_writeback.sql and batch<N>_rollback.sql.
Nothing here connects to a database; the SQL files are run by hand with psql.
"""
import argparse
import csv
import sqlite3
from pathlib import Path

CSV_FIELDS = ("metric_url_id", "query_id", "tags", "rank", "old_url", "new_url")


def load_rows(state_path: str) -> list[dict]:
    con = sqlite3.connect(state_path)
    unresolved = con.execute(
        "SELECT count(*) FROM golden g JOIN goto t ON t.url = g.url "
        "WHERE t.status IS NOT 'resolved'"
    ).fetchone()[0]
    if unresolved:
        raise SystemExit(f"{unresolved} goto rows are not resolved yet; finish resolving first")
    rows = con.execute(
        """SELECT g.id, g.query_id, g.tags, g.rank, g.url, t.location
             FROM golden g JOIN goto t ON t.url = g.url
            WHERE t.status = 'resolved'
            ORDER BY g.id"""
    ).fetchall()
    return [dict(zip(CSV_FIELDS, r)) for r in rows]


def sql_literal(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def render_sql(rows: list[dict], batch: int, rollback: bool) -> str:
    """One transaction: load the pairs, check every row still holds the expected URL,
    update, then check the batch's counts. Any mismatch aborts without changes."""
    src, dst = ("new_url", "old_url") if rollback else ("old_url", "new_url")
    n = len(rows)
    values = ",\n".join(
        f"({r['metric_url_id']}, {sql_literal(r[src])}, {sql_literal(r[dst])})" for r in rows
    )
    action = "Restore the google.com/goto URLs" if rollback else "Write resolved google.com/goto URLs"
    after_check = (
        f"IF m <> {n} THEN RAISE EXCEPTION 'expected {n} goto rows after rollback, found %', m; END IF;"
        if rollback else
        "IF m <> 0 THEN RAISE EXCEPTION 'expected no goto rows left, found %', m; END IF;"
    )
    return f"""-- {action} into metric_url for batch {batch} ({n} rows).
-- Generated by scripts/golden_goto_writeback/build_writeback.py; do not edit by hand.
--
--   psql -v ON_ERROR_STOP=1 -h 172.16.191.1 -p 5433 -U metric -d metricdb -f <this file>
--
-- Runs in one transaction. It aborts, changing nothing, unless all {n} rows still
-- hold the expected URL. Only metric_url.url changes; run
-- `measure.py --test --measure crawler_all --strategy random head` (no --create)
-- afterwards to recompute the flags and coverage, see README.md.

BEGIN;

CREATE TEMP TABLE goto_writeback (
    id      bigint PRIMARY KEY,
    old_url text NOT NULL,
    new_url text NOT NULL
) ON COMMIT DROP;

INSERT INTO goto_writeback (id, old_url, new_url) VALUES
{values};

DO $$
DECLARE n int;
BEGIN
    SELECT count(*) INTO n
      FROM metric_url u
      JOIN metric_queries q ON q.id = u.query_id
      JOIN goto_writeback w ON w.id = u.id
     WHERE q.batch_id = {batch} AND u.url = w.old_url;
    IF n <> {n} THEN
        RAISE EXCEPTION 'expected {n} batch {batch} rows with the old URL, found %', n;
    END IF;
END $$;

UPDATE metric_url u
   SET url = w.new_url
  FROM goto_writeback w
 WHERE u.id = w.id AND u.url = w.old_url;

DO $$
DECLARE m int;
BEGIN
    SELECT count(*) INTO m
      FROM metric_url u
      JOIN metric_queries q ON q.id = u.query_id
     WHERE q.batch_id = {batch} AND u.url LIKE 'https://www.google.com/goto?%';
    {after_check}
END $$;

COMMIT;
"""


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--state", required=True, help="SQLite state file from resolve_golden_goto.py")
    p.add_argument("--batch", type=int, required=True)
    p.add_argument("--out", default=str(Path(__file__).parent))
    args = p.parse_args()

    rows = load_rows(args.state)
    out = Path(args.out)
    with open(out / f"batch{args.batch}_goto_resolved.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=CSV_FIELDS)
        w.writeheader()
        w.writerows(rows)
    (out / f"batch{args.batch}_writeback.sql").write_text(render_sql(rows, args.batch, rollback=False))
    (out / f"batch{args.batch}_rollback.sql").write_text(render_sql(rows, args.batch, rollback=True))
    print(f"wrote {len(rows)} rows for batch {args.batch} to {out}")


if __name__ == "__main__":
    main()
